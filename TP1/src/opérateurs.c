#include <stdio.h>
#include <stdbool.h>

int main(void) {
    int a = 16;
    int b = 3;

    /* Opérateurs arithmétiques /
    printf("a + b = %d\n", a + b);
    printf("a - b = %d\n", a - b);
    printf("a b = %d\n", a * b);
    printf("a / b = %d\n", a / b);
    printf("a %% b = %d\n", a % b);

    /* Opérateurs de comparaison (booléens) */
    printf("a == b : %s\n", (a == b) ? "true" : "false");
    printf("a > b  : %s\n", (a > b) ? "true" : "false");

    return 0;
}

